function storedLanguage(): string | null {
  try {
    return window.localStorage.getItem("orion.lang");
  } catch {
    return null;
  }
}

void i18n.use(initReactI18next).init({
  resources,
  lng: storedLanguage() ?? "en",
  fallbackLng: "en",
  interpolation: { escapeValue: false },
});

export default i18n;
